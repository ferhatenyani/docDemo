export const dicts: Record<Locale, Dict> = { fr, ar };

export function t(locale: Locale, key: string): string {
  return dicts[locale]?.[key] ?? fr[key] ?? key;
}

// -------------------------------------------------------------
// React hook — sugar so pages can write `const t = useT()`
// -------------------------------------------------------------
export function useT() {
  const locale = useApp((s) => s.locale);
  const fn = (key: string) => t(locale, key);
  fn.locale = locale;
  return fn as ((key: string) => string) & { locale: Locale };
}

export function useLocale(): Locale {
  return useApp((s) => s.locale);
}
